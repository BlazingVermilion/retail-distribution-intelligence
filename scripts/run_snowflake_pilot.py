"""Configure local key-pair authentication and run the isolated step 12B dbt project."""
import argparse
import base64
import getpass
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "dbt_snowflake"
ART = ROOT / "artifacts/snowflake/2026-09"
KEY = Path.home() / ".snowflake" / "rdi_pilot_key.p8"
FIELDS = "rows_n unique_ids stores bottles_n dollars_n liters_n bottles_sum dollars_sum liters_sum".split()


def reference():
    # Consume only the fixed, numeric expected-value list generated in step 12A.
    # Never execute or splice arbitrary SQL from the comparison file into dbt.
    sql = (ART / "003_compare.sql").read_text(encoding="utf-8")
    found = re.search(r"\be AS \(SELECT ([^()]+)\)\s*SELECT IFF", sql)
    if not found:
        raise ValueError("Unrecognized reference. Use the comparison SQL generated by step 12A.")
    values = {}
    for part in found[1].split(","):
        m = re.fullmatch(r"\s*(NULL|-?\d+(?:\.\d+)?) AS ([a-z_]+)\s*", part)
        if not m or m[2] in values:
            raise ValueError("Invalid or duplicate metric in the reference.")
        values[m[2]] = m[1]
    if set(values) != set(FIELDS):
        raise ValueError("The nine expected metrics are required.")
    return values


def setup():
    from cryptography.hazmat.primitives import serialization as ser
    from cryptography.hazmat.primitives.asymmetric import rsa
    KEY.parent.mkdir(parents=True, exist_ok=True)
    if not KEY.exists():
        pw = getpass.getpass("Choose a passphrase for this local key: ")
        if len(pw) < 12 or pw != getpass.getpass("Confirm passphrase: "):
            raise ValueError("Use matching passphrases with at least 12 characters.")
        k = rsa.generate_private_key(public_exponent=65537, key_size=2048)
        data = k.private_bytes(ser.Encoding.PEM, ser.PrivateFormat.PKCS8, ser.BestAvailableEncryption(pw.encode()))
        with os.fdopen(os.open(KEY, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600), "wb") as f:
            f.write(data)
    else:
        k = ser.load_pem_private_key(KEY.read_bytes(), password=getpass.getpass("Existing key passphrase: ").encode())
    public = base64.b64encode(k.public_key().public_bytes(ser.Encoding.DER, ser.PublicFormat.SubjectPublicKeyInfo)).decode()
    ART.mkdir(parents=True, exist_ok=True)
    dest = ART / "004_setup_dbt_role.sql"
    # No OR REPLACE: never reset an existing user's keys. Only the public key leaves this machine.
    dest.write_text(f"""USE ROLE SYSADMIN;
CREATE SCHEMA IF NOT EXISTS RDI_PILOT_DB.DBT_PILOT;
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS RDI_DBT_PILOT_ROLE;
GRANT ROLE RDI_DBT_PILOT_ROLE TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE RDI_PILOT_WH TO ROLE RDI_DBT_PILOT_ROLE;
GRANT USAGE ON DATABASE RDI_PILOT_DB TO ROLE RDI_DBT_PILOT_ROLE;
GRANT USAGE ON SCHEMA RDI_PILOT_DB.PILOT TO ROLE RDI_DBT_PILOT_ROLE;
GRANT SELECT ON TABLE RDI_PILOT_DB.PILOT.IOWA_SEP_2026 TO ROLE RDI_DBT_PILOT_ROLE;
GRANT USAGE, CREATE VIEW, CREATE TABLE ON SCHEMA RDI_PILOT_DB.DBT_PILOT TO ROLE RDI_DBT_PILOT_ROLE;
CREATE USER IF NOT EXISTS RDI_DBT_PILOT_SVC TYPE=SERVICE RSA_PUBLIC_KEY='{public}' DEFAULT_ROLE=RDI_DBT_PILOT_ROLE;
GRANT ROLE RDI_DBT_PILOT_ROLE TO USER RDI_DBT_PILOT_SVC;
""", encoding="utf-8")
    print("Run this generated SQL in your personal Snowflake pilot account:", dest)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("setup","debug","build"))
    action = parser.parse_args().action
    if action == "setup":
        setup()
        return 0
    ref = reference()
    env = os.environ.copy()
    if not env.get("RDI_SF_ACCOUNT") or not KEY.exists():
        raise ValueError("Set RDI_SF_ACCOUNT and complete setup first.")
    env.update(RDI_SF_KEY=str(KEY), DBT_ENV_SECRET_RDI_PASSPHRASE=getpass.getpass("Local private key passphrase: "),
               DBT_LOG_PATH=str(ART/"dbt_logs"), DBT_TARGET_PATH=str(ART/"dbt_target"),
               DBT_SEND_ANONYMOUS_USAGE_STATS="false")
    exe = Path(sys.executable).with_name("dbt.exe" if os.name == "nt" else "dbt")
    return subprocess.call([str(exe),action,"--project-dir",str(PROJECT),"--profiles-dir",str(PROJECT),
                            "--vars",json.dumps({"pilot_reference":ref})], env=env, cwd=ROOT)


if __name__ == "__main__":
    sys.exit(main())
